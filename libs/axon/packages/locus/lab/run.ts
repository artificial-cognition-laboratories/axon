#!/usr/bin/env bun
import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { e1 } from "./e1-scale"
import { e2 } from "./e2-redundancy"
import { e2b } from "./e2b-signal-ratio"
import { e4 } from "./e4-coverage"
import { e5 } from "./e5-jev"
import { e6 } from "./e6-linking"

/**
 * The lab runner.
 *
 * Results are COMMITTED and `summary.md` is GENERATED from the JSON — never
 * hand-written, so the write-up cannot drift from what actually ran.
 */
const EXPERIMENTS = {
    e1: e1,
    e2: e2,
    e2b: e2b,
    e4: e4,
} as const

/**
 * Experiments that call a model over the network. Never part of `all`: they
 * cost money and their answers are not seeded. Each writes its own
 * `<name>.md` beside its JSON rather than the generated summary, which holds
 * only the offline experiments.
 */
const ONLINE = {
    e5: e5,
    e6: e6,
} as const

type Name = keyof typeof EXPERIMENTS

const requested = process.argv[2] ?? "all"

if (requested in ONLINE) {
    const dir = join(import.meta.dir, "results")
    mkdirSync(dir, { recursive: true })
    console.log(`\n── ${requested} ──`)
    const started = Date.now()
    const result = await ONLINE[requested as keyof typeof ONLINE]()
    const seconds = ((Date.now() - started) / 1000).toFixed(1)
    const ran = new Date().toISOString()
    writeFileSync(join(dir, `${result.name}.json`), JSON.stringify({ ran: ran, seconds: Number(seconds), rows: result.rows }, null, 2))
    writeFileSync(join(dir, `${result.name}.md`), `# ${result.name}\n\n_Generated by \`bun run lab ${requested}\`. Do not edit._\n\nRan ${ran}, in ${seconds}s.\n\n${result.markdown}\n`)
    console.log(`  → results/${result.name}.md (${seconds}s)`)
    process.exit(0)
}

const names: Name[] = requested === "all" ? (Object.keys(EXPERIMENTS) as Name[]) : [requested as Name]

if (!names.every(name => name in EXPERIMENTS)) {
    console.error(`unknown experiment "${requested}" — try: ${[...Object.keys(EXPERIMENTS), ...Object.keys(ONLINE)].join(", ")}, all`)
    process.exit(1)
}

const dir = join(import.meta.dir, "results")
mkdirSync(dir, { recursive: true })

const sections: string[] = []

for (const name of names) {
    console.log(`\n── ${name} ──`)
    const started = Date.now()
    const result = await EXPERIMENTS[name]()
    const seconds = ((Date.now() - started) / 1000).toFixed(1)

    writeFileSync(
        join(dir, `${result.name}.json`),
        JSON.stringify({ ran: new Date().toISOString(), seconds: Number(seconds), rows: result.rows }, null, 2)
    )
    sections.push(`## ${result.name}\n\nRan in ${seconds}s.\n\n${result.markdown}\n`)
    console.log(`  → results/${result.name}.json (${seconds}s)`)
}

writeFileSync(
    join(dir, "summary.md"),
    `# Lab results\n\n_Generated by \`bun run lab\`. Do not edit._\n\nRan ${new Date().toISOString()}\n\n${sections.join("\n")}`
)
console.log("\n→ results/summary.md")
