import { join } from "node:path"
import { existsSync, readFileSync } from "node:fs"
import { writeDts } from "./write"

/**
 * Parse keys from a .env file. Handles comments, blank lines, and quoted values.
 * Returns only the key names — values are not extracted (they're secrets).
 */
function parseEnvKeys(content: string): string[] {
    const keys: string[] = []
    for (const line of content.split("\n")) {
        const trimmed = line.trim()
        if (!trimmed || trimmed.startsWith("#")) continue
        const eq = trimmed.indexOf("=")
        if (eq === -1) continue
        const key = trimmed.slice(0, eq).trim()
        if (/^[A-Z_][A-Z0-9_]*$/i.test(key)) keys.push(key)
    }
    return keys
}

/**
 * Generate .agent/env.d.ts — typed ProcessEnv augmentation.
 *
 * Reads the agent's .env file and produces a NodeJS.ProcessEnv augmentation that
 * makes `process.env.MY_KEY` resolve to `string | undefined` (or `string` for keys
 * the agent explicitly declares as required via env.needs — future enhancement).
 *
 * This makes `process.env` type-safe in tools, scripts, hooks, and server routes:
 * unknown keys are a type error, known keys get correct string types.
 *
 * Returns the number of env keys typed.
 */
export function generateEnvTypes(agentPath: string): number {
    const envPath = join(agentPath, ".env")
    if (!existsSync(envPath)) return 0

    const keys = parseEnvKeys(readFileSync(envPath, "utf-8"))
    if (keys.length === 0) return 0

    const lines: string[] = [
        "// .agent/env.d.ts — generated by axon prepare, do not edit",
        "// Re-run `axon prepare` after adding keys to .env.",
        "",
        "// Augments ProcessEnv so process.env keys declared in .env are typed.",
        "// Values are always string | undefined — the key is present but may be unset.",
        "declare namespace NodeJS {",
        "    interface ProcessEnv {",
    ]

    for (const key of keys) {
        lines.push(`        ${key}?: string`)
    }

    lines.push("    }", "}", "", "export {}", "")

    writeDts(agentPath, "env.d.ts", lines.join("\n"))
    return keys.length
}
