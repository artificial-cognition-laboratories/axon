import { relative } from "node:path"
import type { AxonModule } from "@arcforge/types"
import { Components } from "../../blueprint"
import { writeDts } from "./write"

/**
 * .agent/components.d.ts — Vue GlobalComponents declarations for prompt
 * components, so they auto-import in prompt templates. Agent components
 * win over module components on name collision (same precedence as every
 * other surface).
 */
export async function generateComponentTypes(root: string, modules: AxonModule[]): Promise<number> {
    const byName = new Map<string, string>() // name → filePath

    // Module components first — agent overwrites on collision.
    for (const mod of modules) {
        for (const entry of (await Components(mod.root)).entries) {
            byName.set(entry.name, entry.filePath)
        }
    }
    for (const entry of (await Components(root)).entries) {
        byName.set(entry.name, entry.filePath)
    }

    if (byName.size === 0) return 0

    const lines: string[] = [
        "// .agent/components.d.ts — generated by axon prepare, do not edit",
        "// Re-run `axon prepare` after adding or removing prompt components.",
        "",
        "declare module 'vue' {",
        "    interface GlobalComponents {",
    ]

    for (const [name, filePath] of byName) {
        // Import path relative to .agent/ where this file lives.
        const rel = relative(root, filePath).replace(/\\/g, "/")
        lines.push(`        ${name}: typeof import("../${rel}")["default"]`)
    }

    lines.push("    }", "}", "", "export {}", "")

    writeDts(root, "components.d.ts", lines.join("\n"))
    return byName.size
}
