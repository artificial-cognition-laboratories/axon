import { join } from "node:path"
import { writeFileSync } from "node:fs"
import { Frame } from "../../frame"

/**
 * globals.d.ts for prompt packages — the ambient surface of
 * `prompt.config.ts`, which is the only code a prompt package has.
 *
 * `PromptConfig` is inlined rather than imported from @arcforge/types. A
 * prompt package is text: it declares no dependencies and installs no
 * node_modules, so there is nothing on disk for an import to resolve
 * through. Duplicating one type is the price of a package that typechecks
 * with an empty directory beside it — and the type is part of the published
 * registry contract, so it changes about as often as the config file format
 * itself. It must stay in step with @arcforge/types/src/prompts.ts.
 */
export const PROMPT_DTS = `// Generated by axon prepare — do not edit.
// Ambient globals for prompt.config.ts. Implemented by the CLI that reads it.

declare global {
    /**
     * A prompt package's marker. Empty: identity (name, version, description)
     * lives in package.json, which is what the registry reads.
     */
    type PromptConfig = Record<string, never>

    /** identity declaration — prompt.config.ts only */
    function definePrompt(config: PromptConfig): { _kind: "prompt", config: PromptConfig }
}

export {}
`

export function generatePromptDts(promptPath: string): void {
    writeFileSync(
        join(Frame({ root: promptPath, kind: "prompt" }).ensure("types"), "globals.d.ts"),
        PROMPT_DTS,
        "utf-8",
    )
}
