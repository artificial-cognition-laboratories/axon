import type { AxonPrompt } from "@arcforge/types"
import { writeDts } from "./write"

function propsType(props: NonNullable<AxonPrompt["props"]>): string {
    if (props.length === 0) return "Record<string, never>"
    return `{ ${props.map(p => `${p.name}${p.required ? "" : "?"}: ${p.type}`).join("; ")} }`
}

/**
 * .agent/prompts.d.ts — AxonPromptMap augmentation. Makes
 * axon.prompt(name, props) fully typed: autocomplete on names,
 * validation on props.
 */
export function generatePromptTypes(root: string, prompts: AxonPrompt[]): number {
    if (prompts.length === 0) return 0

    const lines: string[] = [
        "// .agent/prompts.d.ts — generated by axon prepare, do not edit",
        "// Re-run `axon prepare` after adding or modifying prompts.",
        "",
        'import "@arcforge/types"',
        'declare module "@arcforge/types" {',
        "    interface AxonPromptMap {",
    ]

    for (const prompt of prompts) {
        const type = prompt.props && prompt.props.length > 0 ? propsType(prompt.props) : "Record<string, never>"
        if (prompt.description) lines.push(`        /** ${prompt.description} */`)
        lines.push(`        "${prompt.name}": ${type}`)
    }

    lines.push("    }", "}", "", "export {}", "")

    writeDts(root, "prompts.d.ts", lines.join("\n"))
    return prompts.length
}
