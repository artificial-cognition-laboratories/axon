import { existsSync, mkdirSync, readFileSync } from "node:fs"
import { join, relative } from "node:path"
import type { AxonPrompt, AxonScript } from "@arcforge/types"
import { writeIfChanged } from "./write"

/**
 * Give repository-authored workspace scripts the same ambient frame as the
 * linked agent that will execute them. The config is authored once; .axon/
 * is derived from the currently prepared agent and deliberately disposable.
 */
export function generateWorkspaceScriptFrame(
    workspace: string,
    agentRoot: string,
    scripts: AxonScript[],
    prompts: AxonPrompt[],
): void {
    const scriptsDir = join(workspace, "scripts")
    if (!existsSync(scriptsDir)) return

    const output = join(workspace, ".axon")
    mkdirSync(output, { recursive: true })

    const config = join(workspace, "tsconfig.json")
    // The initial workspace frame used an extends-only config. Upgrade that
    // exact generated shape, but never overwrite a workspace author's config.
    const legacyConfig = existsSync(config) && (() => {
        try {
            const parsed = JSON.parse(readFileSync(config, "utf-8")) as { extends?: string }
            return parsed.extends === "@arcforge/types/tsconfig.base.json"
        } catch {
            return false
        }
    })()
    if (!existsSync(config) || legacyConfig) {
        writeIfChanged(config, JSON.stringify({
            compilerOptions: {
                // Workspace scripts are Bun modules even when a script has no
                // imports/exports. This makes top-level await valid without
                // requiring authors to add a meaningless module marker.
                target: "ESNext",
                module: "ESNext",
                moduleResolution: "bundler",
                moduleDetection: "force",
                lib: ["ESNext"],
                types: ["bun-types"],
                strict: true,
                skipLibCheck: true,
                noEmit: true,
                allowImportingTsExtensions: true,
            },
            include: ["scripts/**/*.ts", ".axon/**/*.d.ts"],
        }, null, 2) + "\n")
    }

    const toolGlobals = join(agentRoot, ".agent", "types", "tool-globals.d.ts")
    const references = existsSync(toolGlobals)
        ? [`/// <reference path="${relative(output, toolGlobals).replace(/\\\\/g, "/")}" />`]
        : []

    // This is intentionally a small stable script contract rather than a
    // reference to the agent's complete axon.d.ts. Referencing that declaration
    // pulls the agent's provider graph into repository typechecking; a workspace
    // script needs its runtime entrypoints and the selected agent's tool globals.
    const workspacePrompts = prompts.filter(prompt => prompt.name.startsWith("workspace:"))
    const propsType = (props: NonNullable<AxonPrompt["props"]>): string =>
        props.length === 0
            ? "Record<string, never>"
            : `{ ${props.map(prop => `${prop.name}${prop.required ? "" : "?"}: ${prop.type}`).join("; ")} }`
    const promptTypes = workspacePrompts.map(prompt =>
        `    interface WorkspacePromptMap { "${prompt.name}": ${propsType(prompt.props ?? [])} }`,
    )

    const scriptGlobals = [
        "declare global {",
        "    interface WorkspacePromptMap {}",
        ...promptTypes,
        "    type WorkspacePromptName = keyof WorkspacePromptMap",
        "    type WorkspacePromptArgs<K extends WorkspacePromptName> = keyof WorkspacePromptMap[K] extends never",
        "        ? [props?: WorkspacePromptMap[K]]",
        "        : [props: WorkspacePromptMap[K]]",
        "    const axon: {",
        "        request(input: string | { prompt: string }): Promise<unknown>",
        "        prompt<K extends string>(name: K & (K extends WorkspacePromptName ? K : K extends `workspace:${string}` ? never : K), ...args: K extends WorkspacePromptName ? WorkspacePromptArgs<K> : [props?: Record<string, unknown>]): Promise<string>",
        "        scripts: { request(name: string, args?: Record<string, unknown>): Promise<unknown> }",
        "    }",
        "    const args: Record<string, unknown>",
        "    function defineArgs<T extends Record<string, unknown>>(): T",
        "}",
    ]
    // Keep a workspace-only inventory too: it names the files this workspace
    // owns even when the selected agent has other script surfaces.
    const workspaceNames = scripts
        .filter(script => script.name.startsWith("workspace:"))
        .map(script => script.name)

    writeIfChanged(join(output, "globals.d.ts"), [
        "// .agents/.axon/globals.d.ts — generated by axon prepare, do not edit",
        "// The selected agent supplies the runtime globals and tool surface.",
        ...references,
        ...scriptGlobals,
        "",
        "export {}",
        "",
    ].join("\n"))

    writeIfChanged(join(output, "scripts.d.ts"), [
        "// .agents/.axon/scripts.d.ts — generated by axon prepare, do not edit",
        `// Workspace scripts: ${workspaceNames.join(", ") || "none"}`,
        "",
        "export {}",
        "",
    ].join("\n"))
}
