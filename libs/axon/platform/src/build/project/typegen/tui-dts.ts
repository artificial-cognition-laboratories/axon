import { join } from "node:path"
import { writeFileSync } from "node:fs"
import { TUI_CONTRACT } from "@arcforge/types/tui-contract"
import { Frame, type ProjectKind } from "../../frame"

/**
 * The ambient authoring surface for a PROFILE and for EXTENSIONS — the ten
 * globals a user's `main.ts`, `plugins/` and `extensions/` are written
 * against, plus `defineProfile`/`defineExtension`.
 *
 * ── Why this file reads a constant instead of holding the text ───────────────
 *
 * The other ambient frames (cognet, prompt) inline their declarations as a
 * template literal and carry a "must stay in lockstep with X" comment. That is
 * a manual sync, and it is affordable there because both surfaces are small and
 * change about as often as the config file format itself.
 *
 * The TUI contract is neither: it is the whole extension API, it is the thing
 * this feature exists to expose, and it will change while the API settles. A
 * hand-maintained copy of it would drift the first week. So `@arcforge/types`
 * exports its own source text as `TUI_CONTRACT` (generated from
 * `src/tui.ts` at build time — see that package's `scripts/contract.ts`), and
 * this writer only wraps it. One authored file, no duplicate to keep in step.
 *
 * The wrapping is what makes it ambient: `tui.ts` is an ordinary module of
 * exported types, and a profile needs those same types as globals. `export`
 * is stripped and the whole thing goes inside `declare global`.
 *
 * The trailing `export {}` is load-bearing. It makes globals.d.ts a module, so
 * `declare global` is legal — and it is also what lets `moduleDetection: force`
 * (from tsconfig.base.json) treat a user's import-free `main.ts` as a module,
 * which is what makes top-level `await` work there. Removing it breaks both.
 */
function tuiDts(): string {
    return `// Generated by axon prepare — do not edit.
// Ambient globals for a profile's main.ts, plugins/ and extensions/.
// Source: @arcforge/types/src/tui.ts

declare global {
${TUI_CONTRACT}

    // ── The globals themselves ───────────────────────────────────────────────
    //
    // Ten, deliberately: everything reachable from the keyboard, and nothing
    // more. They are ambient rather than imported because that is the authoring
    // DX the rest of the platform already uses (cognet's loop/kernel/phase,
    // a prompt's definePrompt) — and because an extension cannot import from a
    // minified CLI bundle, so a handle it must reach for could not be typed.

    /** The terminal itself — navigation, notifications, lifecycle hooks. */
    const tui: AxonTui
    /** The interaction primitive — registered palettes, and pick/confirm/prompt. */
    const palette: AxonPalette
    /** The \`:\` command tree. */
    const commands: AxonCommands
    /** Key chords. */
    const keys: AxonKeys
    /** Mode switching. */
    const mode: AxonMode
    /** The message box. */
    const input: AxonInput
    /** Agent instances — spawn by name, everything else by instance. */
    const agents: AxonAgents
    /** The terminal's colours, and switching between them. */
    const theme: AxonTheme
    /** The configurable rows above the input bar. */
    const lines: AxonLines
    /** The live values a line can show. */
    const components: AxonComponents

    /** identity declaration — extension.config.ts only */
    function defineExtension(config?: ExtensionConfig): ExtensionDefinition

    /** identity declaration — profile.config.ts only */
    function defineProfile(config: ProfileConfig): ProfileDefinition

    /**
     * Provider factories — what \`providers:\` takes.
     *
     * Declared here rather than imported: a profile directory has no
     * node_modules to resolve through, which is the same constraint the whole
     * frame is built around. The shapes are spelled out for the same reason
     * ProviderEntry itself is spelled out in tui.ts.
     */
    function Axon(options?: ProviderOptions): ProviderEntry
    function Local(options?: ProviderOptions): ProviderEntry
    function Local(options?: ProviderOptions): ProviderEntry
    function Codex(options?: ProviderOptions): ProviderEntry
    function OpenRouter(options?: ProviderOptions): ProviderEntry
    function Ollama(options?: ProviderOptions): ProviderEntry
    function HuggingFace(options?: ProviderOptions): ProviderEntry
    function Mock(script?: unknown): ProviderEntry

    type ProviderOptions = {
        /** Own credential, for a user supplying one rather than connecting their account. */
        key?: string
        /** Endpoint override — self-hosted daemons, local harnesses. */
        url?: string
        /** Ceiling on concurrent calls a fanned-out role may spend here. */
        slots?: number
    }
}

export {}
`
}

/**
 * Write globals.d.ts into a profile's or an extension's type frame.
 *
 * Both kinds get the SAME surface. An extension is a profile's main.ts
 * packaged — if an extension could not express what a user's own config can,
 * every gap would become a feature request, so there is one contract and one
 * writer rather than a privileged internal surface and a reduced public one.
 */
export function generateTuiDts(root: string, kind: ProjectKind): void {
    writeFileSync(
        join(Frame({ root, kind }).ensure("types"), "globals.d.ts"),
        tuiDts(),
        "utf-8",
    )
}
