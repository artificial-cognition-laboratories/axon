import { join } from "node:path"
import { writeFileSync } from "node:fs"
import { Frame, type ProjectKind } from "../../frame"
import { emptyRegistrations, mergeRegistrations, scanSource, type Registration, type Registrations } from "../../extensions/registrations"

/**
 * `.axon/types/registry.d.ts` — what a config actually registered, as types.
 *
 * ── What this buys ──────────────────────────────────────────────────────────
 *
 * `lines.set(["me:statuz"])` was a runtime fault reported after boot. It is now
 * a red squiggle while you type it, and `me:` completes to whatever you
 * declared in that same file. The same holds for palettes and commands, which
 * were string-addressed with no completion at all.
 *
 * ── Built-ins and your own are the SAME tier ────────────────────────────────
 *
 * Both land in one registry through declaration merging, so nothing about a
 * built-in is more discoverable than something you wrote four lines up. That
 * has been the rule everywhere else in this API — a built-in is a registration
 * the terminal happened to make — and generating types is where it would have
 * been easiest to quietly break.
 *
 * ── Regenerated, never appended ─────────────────────────────────────────────
 *
 * The file is written whole on every run. A name you delete has to stop
 * completing, and a merge step would keep it forever.
 */

/** Axon's own catalogue — the names the TUI registers at boot. */
export type BuiltinRegistry = {
    components: readonly string[]
    lines: readonly string[]
}

function entries(registrations: readonly Registration[], indent = "        "): string[] {
    const out: string[] = []
    for (const entry of registrations) {
        if (entry.description) {
            const summary = entry.description.split("\n")[0]!.trim()
            if (summary) out.push(`${indent}/** ${summary.replace(/\*\//g, "*\\/")} */`)
        }
        out.push(`${indent}${JSON.stringify(entry.name)}: true`)
    }
    return out
}

function block(name: string, registrations: readonly Registration[]): string[] {
    // An empty interface still emits: reopening it with nothing is harmless and
    // keeps the generated file's shape stable, which makes a diff between two
    // runs readable.
    return [`    interface ${name} {`, ...entries(registrations), "    }"]
}

/**
 * Write the registry declarations for one profile or extension.
 *
 * `sources` are the roots to scan, in LOAD ORDER — the profile first, then each
 * extension as `profile.config.ts` lists them. Order decides which description
 * survives a duplicate name, matching the loader's own first-wins rule.
 */
export function generateRegistryDts(
    root: string,
    kind: ProjectKind,
    sources: readonly string[],
    builtins: BuiltinRegistry = { components: [], lines: [] },
): void {
    const scanned = sources.map(scanSource)

    // Built-ins go FIRST so their documentation wins a collision with a config
    // that shadowed the name — the shadow is a mistake worth leaving legible.
    const builtinRegistrations: Registrations = {
        ...emptyRegistrations(),
        components: builtins.components.map(name => ({ name })),
        lines: builtins.lines.map(name => ({ name })),
    }

    const all = mergeRegistrations([builtinRegistrations, ...scanned])

    /**
     * `declare global`, NOT `declare module "@arcforge/types"`.
     *
     * The contract is INLINED into globals.d.ts inside a `declare global`
     * block — a profile has no node_modules for a module augmentation to
     * resolve through, which is the same constraint that keeps tui.ts
     * import-free. So the registries are global interfaces, and reopening them
     * has to happen in the same scope or the two declarations never meet: the
     * file typechecks, the union stays empty, and nothing completes.
     */
    const lines = [
        "// Generated by axon prepare — do not edit.",
        "// What this profile and its extensions register, as completable names.",
        "//",
        "// Reopens the registry interfaces declared in globals.d.ts. Both live in",
        "// `declare global` because a profile has no node_modules to augment through.",
        "",
        "declare global {",
        ...block("AxonComponentRegistry", all.components),
        ...block("AxonLineRegistry", all.lines),
        ...block("AxonPaletteRegistry", all.palettes),
        ...block("AxonCommandRegistry", all.commands),
        "}",
        "",
        "export {}",
        "",
    ]

    writeFileSync(join(Frame({ root, kind }).ensure("types"), "registry.d.ts"), lines.join("\n"), "utf-8")
}
