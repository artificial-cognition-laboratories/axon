import type { AxonScript } from "@arcforge/types"
import { writeDts } from "./write"

function argsType(args: NonNullable<AxonScript["args"]>): string {
    if (args.length === 0) return "Record<string, never>"
    return `{ ${args.map(a => `${a.name}${a.required ? "" : "?"}: ${a.type}`).join("; ")} }`
}

/**
 * .agent/scripts.d.ts — AxonScriptMap augmentation. Makes
 * axon.scripts.request(name, args) fully typed.
 */
export function generateScriptTypes(root: string, scripts: AxonScript[]): number {
    if (scripts.length === 0) return 0

    const lines: string[] = [
        "// .agent/scripts.d.ts — generated by axon prepare, do not edit",
        "// Re-run `axon prepare` after adding or modifying scripts.",
        "",
        'import "@arcforge/types"',
        'declare module "@arcforge/types" {',
        "    interface AxonScriptMap {",
    ]

    for (const script of scripts) {
        const type = script.args && script.args.length > 0 ? argsType(script.args) : "Record<string, never>"
        if (script.args && script.args.length > 0) {
            lines.push(`        /** Args: ${script.args.map(a => `${a.name}${a.required ? "" : "?"}: ${a.type}`).join(", ")} */`)
        }
        lines.push(`        "${script.name}": { args: ${type}; return: unknown }`)
    }

    lines.push("    }", "}", "", "export {}", "")

    writeDts(root, "scripts.d.ts", lines.join("\n"))
    return scripts.length
}
