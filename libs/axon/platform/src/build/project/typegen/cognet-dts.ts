import { join } from "node:path"
import { writeFileSync } from "node:fs"
import { Frame, type ProjectKind } from "../../frame"

/**
 * The ambient authoring surface for cognet source — what the compile step's
 * host installs at runtime (defineCognet, loop, kernel, phase, system), typed
 * here for the editor. Written into the owning project's `types/` area by
 * `axon prepare`: a standalone cognet's own frame, or the AGENT's frame when
 * the brain is inline at `<agent>/cognet/`.
 *
 * Must stay in lockstep with @arcforge/cognet — the host IS this
 * contract's implementation.
 */
export const COGNET_DTS = `// Generated by axon prepare — do not edit.
// Ambient globals for cognet source. Implemented by the compile host
// (@arcforge/cognet); typed here for the editor.
import type {
    AxonStimulusEntry,
    CognetConfig,
    CognetPlugin,
    KernelAbi,
} from "@arcforge/types"

declare global {
    /** what this brain declares (mode, wakeOn, engines) — cognet.config.ts only.
     *  Identity is NOT declared: name and version come from package.json. */
    function defineCognet<T extends CognetConfig>(config: T): T

    /**
     * A lifecycle plugin — plumbing wired to hooks (boot, wake, tick,
     * shutdown), declared in plugins/*.ts. Registers at import time, before
     * the brain boots. PLUMBING ONLY: load/save derived state, warm caches,
     * devtools. Domain facts are stimuli that fold into the world, never hooks.
     */
    function definePlugin(plugin: CognetPlugin): CognetPlugin

    /**
     * THE entry point — declare the tick pipeline once, in src/main.ts.
     * The kernel wakes it per stimulus batch; ticks run until stop() or
     * interrupt. Wake-scoped things arrive as args, never as globals.
     */
    function loop(body: (ctx: {
        /** stimuli committed since the last wake, in seq order — stimulus:* only, the cognet's whole input contract */
        stimuli: readonly AxonStimulusEntry[]
        /** kernel interrupt — honor it between units of work */
        signal: AbortSignal
        /** end the wake after this tick — the brain stays warm */
        stop(): void
    }) => Promise<void> | void): void

    /** the syscall table — live from load() onward; do work inside loop(), not at module top level */
    const kernel: KernelAbi


    /** a named stage within a tick — cognet:phase:* telemetry */
    function phase<T>(name: string, fn: () => Promise<T>): Promise<T>

    /** a unit of work within a phase — timed for the flame graph */
    function system<T>(name: string, fn: () => Promise<T>): Promise<T>
}

export {}
`

/**
 * The cognet authoring surface's filename inside a frame.
 *
 * Named distinctly rather than sharing the generic `globals.d.ts`, because in
 * an agent's frame it sits beside the AGENT's declarations and the two must be
 * separable by glob: the agent's own tsconfig excludes this file, and the
 * inline cognet's tsconfig excludes everything else. Two ambient surfaces in
 * one directory can only coexist if each scope can name the other's files.
 */
export const COGNET_GLOBALS = "cognet-globals.d.ts"

/**
 * Write the cognet authoring surface into a project's frame.
 *
 * `kind` is the OWNING project: a standalone cognet writes into its own
 * `.cognet/types/`, while an agent with an inline `cognet/` writes the same
 * declarations into `.agent/types/` — one brain's authoring surface, reached
 * from whichever frame the source happens to live in.
 */
export function generateCognetDts(root: string, kind: ProjectKind = "cognet"): void {
    writeFileSync(
        join(Frame({ root: root, kind: kind }).ensure("types"), COGNET_GLOBALS),
        COGNET_DTS,
        "utf-8",
    )
}
