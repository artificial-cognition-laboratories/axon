import { existsSync, readFileSync } from "node:fs"
import type { AxonModule } from "@arcforge/types"
import { writeDts } from "./write"

/**
 * .agent/hooks.d.ts — AxonModuleEvents augmentation. Makes
 * `axon.hooks.hook("discord:message.received", ({ content }) => ...)` fully
 * typed in userland: the event name autocompletes and the payload is inferred,
 * with no imports and no generics.
 *
 * The mechanism (chosen over asking authors to export a named emit type):
 * import each module's config by its resolved path and merge the payload types
 * recovered via `typeof Module.emits` into the open AxonModuleEvents interface.
 * `defineModule` is generic over `emits`, so those payloads survive as their
 * declared shapes — the inline `{} as { ... }` IS the single source of truth,
 * no duplicated exported type to drift.
 *
 * Only modules that actually declare `emits` are imported, so an agent's type
 * graph pulls in a module config only when that module has events to type.
 */
export function generateHookTypes(root: string, modules: AxonModule[]): number {
    const withEmits = modules.filter(m => m.configPath && hasEmits(m.configPath))
    if (withEmits.length === 0) return 0

    const lines: string[] = [
        "// .agent/hooks.d.ts — generated by axon prepare, do not edit",
        "// Re-run `axon prepare` after installing or changing modules.",
        "//",
        "// Merges each installed module's `emits` payloads into AxonModuleEvents,",
        "// so axon.hooks.hook(<event>, handler) is typed from the module's own",
        "// declaration — no imports, no generics in your plugin.",
        "",
    ]

    // One `import type` per module, aliased so two modules can't collide, plus
    // a payload alias that unwraps the optional `emits` to a concrete map.
    withEmits.forEach((module, i) => {
        lines.push(`import type __M${i} from ${JSON.stringify(module.configPath)}`)
    })
    lines.push("")
    withEmits.forEach((_, i) => {
        // `__M${i}` is a VALUE (the default export) — recover its emits type
        // via `typeof`. NonNullable unwraps the optional `emits?: E`.
        lines.push(`type __E${i} = NonNullable<(typeof __M${i})["emits"]>`)
    })

    // Merge every module's emit map into the open interface via `extends`.
    // An interface extending object types is exactly declaration merging.
    lines.push(
        "",
        'declare module "@arcforge/types" {',
        `    interface AxonModuleEvents extends ${withEmits.map((_, i) => `__E${i}`).join(", ")} {}`,
        "}",
        "",
        "export {}",
        "",
    )

    writeDts(root, "hooks.d.ts", lines.join("\n"))
    return withEmits.length
}

/** Cheap text check for an `emits` block in a module.config.ts — avoids importing modules that have no events. */
function hasEmits(configPath: string): boolean {
    if (!existsSync(configPath)) return false
    try {
        return /(^|\s)emits\s*:/.test(readFileSync(configPath, "utf-8"))
    } catch {
        return false
    }
}
