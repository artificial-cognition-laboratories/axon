import { existsSync, readFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { err } from "@arcforge/err"

/** The generated crate's manifest — private to Crate. */
export const manifest = {
    /** The author-facing Cargo package created when Rust systems first appear. */
    source(sourceDir: string, agentRoot: string, out: string): string {
        const target = relative(sourceDir, join(out, "systems", "src", "lib.rs"))
        const runtime = relative(sourceDir, join(agentRoot, "node_modules", "@arcforge", "cognet", "rust", "cognet"))
        return [
            "[package]",
            'name = "cognet_systems"',
            'version = "0.0.0"',
            'edition = "2021"',
            "publish = false",
            "",
            "[lib]",
            `path = ${JSON.stringify(target)}`,
            "",
            "[dependencies]",
            `cognet = { path = ${JSON.stringify(runtime)} }`,
            'serde = { version = "1", features = ["derive"] }',
            'serde_json = "1"',
            "",
            "[profile.release]",
            "overflow-checks = true",
            "",
            '[profile.dev.package."*"]',
            "opt-level = 3",
            "",
        ].join("\n")
    },

    /** Keep Cargo and rust-analyzer's build output in the agent frame. */
    config(sourceDir: string, out: string): string {
        return `[build]\ntarget-dir = ${JSON.stringify(relative(sourceDir, join(out, "target")))}\n`
    },

    /**
     * The cognet's own `Cargo.toml`'s `[dependencies]`, as TOML. A crate listed by a
     * relative `path` is resolved against the cognet, where its author wrote it.
     */
    dependencies(path: string, runtime: string, owned: boolean): { text: string; runtime: string } {
        if (!existsSync(path)) throw err("COGNET_NATIVE_FAILED", { detail: `${path} is required for a Rust cognet; add a Cargo package manifest` })
        const parsed: unknown = Bun.TOML.parse(readFileSync(path, "utf8"))
        if (!isTable(parsed)) throw err("COGNET_NATIVE_FAILED", { detail: `${path} is not a TOML table` })
        if (!isTable(parsed.package) || !isTable(parsed.lib)) throw err("COGNET_NATIVE_FAILED", { detail: `${path} must declare [package] and [lib]` })
        const dependencies = parsed.dependencies ?? {}
        if (!isTable(dependencies)) throw err("COGNET_NATIVE_FAILED", { detail: `${path}: [dependencies] is not a table` })
        const cognet = dependencies.cognet
        if (!isTable(cognet) || typeof cognet.path !== "string") throw err("COGNET_NATIVE_FAILED", { detail: `${path}: [dependencies].cognet must be a path dependency` })
        const resolvedRuntime = owned ? resolve(dirname(path), cognet.path) : runtime
        // The crate is generated elsewhere: a crate the cognet lists by a path relative to itself is listed by where it is.
        const located = (value: unknown): unknown => (isTable(value) && typeof value.path === "string" ? { ...value, path: resolve(dirname(path), value.path) } : value)
        const text = Object.entries(dependencies).map(([name, value]) => `${toml.key(name)} = ${toml.value(name === "cognet" ? { ...cognet, path: resolvedRuntime } : located(value), `${path}, ${name}`)}`).join("\n")
        return { text: text, runtime: resolvedRuntime }
    },

    /** The generated workspace: the module, plus a mirrored systems crate for installed cognets. */
    workspace(owned: boolean): string {
        return [
            "# Generated by axon prepare — a cognet's Rust. List crates in the cognet's own Cargo.toml.",
            "[workspace]",
            'resolver = "2"',
            `members = [${owned ? '"module"' : '"systems", "module"'}]`,
            "",
            // The systems are what a cognet runs every tick: optimised as a release build is, and an overflow still a fault.
            "[profile.release]",
            "overflow-checks = true",
            "",
            // A test build of the cognet's own code stays quick to compile; what it calls into — small_gicp's C++, a
            // solver — is optimised even there, or a test of one fit takes a second.
            '[profile.dev.package."*"]',
            "opt-level = 3",
            "",
        ].join("\n")
    },

    /** The systems crate: the cognet's Rust, its schemas' types, and the crates it lists. */
    systems(dependencies: string): string {
        return [
            "[package]",
            'name = "cognet_systems"',
            'version = "0.0.0"',
            'edition = "2021"',
            "publish = false",
            "",
            "[dependencies]",
            dependencies,
            "",
        ].join("\n")
    },

    /** The module crate: the napi boundary over the systems crate, built as the `.node` the bundle loads. */
    module(runtime: string, sourceDir: string | null): string {
        return [
            "[package]",
            'name = "cognet_native"',
            'version = "0.0.0"',
            'edition = "2021"',
            "publish = false",
            "",
            "[lib]",
            'crate-type = ["cdylib"]',
            "",
            "[dependencies]",
            `cognet_systems = { path = ${JSON.stringify(sourceDir ?? "../systems")} }`,
            `cognet = { path = ${JSON.stringify(runtime)} }`,
            'napi = { version = "3", default-features = false, features = ["napi6", "serde-json"] }',
            'napi-derive = "3"',
            "",
            "[build-dependencies]",
            'napi-build = "2"',
            "",
        ].join("\n")
    },
}

/** TOML written back from what `Bun.TOML` read — private to the manifest: strings, numbers, booleans, arrays and inline tables. */
const toml = {
    key(name: string): string {
        return /^[A-Za-z0-9_-]+$/.test(name) ? name : JSON.stringify(name)
    },

    value(value: unknown, where: string): string {
        if (typeof value === "string") return JSON.stringify(value)
        if (typeof value === "number" || typeof value === "boolean") return String(value)
        if (Array.isArray(value)) return `[${value.map(one => toml.value(one, where)).join(", ")}]`
        if (isTable(value)) return `{ ${Object.entries(value).map(([key, one]) => `${toml.key(key)} = ${toml.value(one, where)}`).join(", ")} }`
        throw err("COGNET_NATIVE_FAILED", { detail: `${where}: ${JSON.stringify(value)} is no value a dependency is listed with` })
    },
}

function isTable(value: unknown): value is Record<string, unknown> {
    return typeof value === "object" && value !== null && !Array.isArray(value)
}
