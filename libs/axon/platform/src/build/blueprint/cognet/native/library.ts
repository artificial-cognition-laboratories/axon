import type { RustSource } from "./crate"
import { join, relative } from "node:path"

/**
 * The generated crates' `lib.rs` — private to Crate. Two crates, because a
 * napi module cannot be tested: its test binary would need napi's symbols,
 * which only a JavaScript host has. So the systems and the schemas' types are
 * plain Rust (`cognet_systems`, which `cargo test` runs), and the module the
 * bundle loads (`cognet_native`) is only the boundary.
 */
export const library = {
    /** The schemas, every file mounted at its path, and the list of systems the module serves. */
    systems(sources: readonly RustSource[], root: string): string {
        const tree: Mount = { files: [], folders: new Map() }
        for (const source of sources) {
            let node = tree
            for (const folder of source.module.slice(0, -1)) {
                const next = node.folders.get(folder) ?? { files: [], folders: new Map() }
                node.folders.set(folder, next)
                node = next
            }
            node.files.push({ name: source.module.at(-1)!, absPath: source.absPath })
        }
        const systems = sources.flatMap(source => (source.system ? [{ name: source.system, path: source.module.join("::") }] : []))
        return [
            "// Generated by axon prepare — this cognet's Rust, mounted at the paths it sits at, and the types its schemas declare. Edit those, not this file.",
            "#![allow(non_snake_case, dead_code)]",
            "",
            "/// The types and handles generated from the cognet's schemas.",
            "pub mod schema;",
            "",
            ...library.mount(tree, "", root, []),
            "",
            "/// Every system, by the name it runs as.",
            "pub const SYSTEMS: &[cognet::Served] = &[",
            ...systems.map(system => `    cognet::Served { name: ${JSON.stringify(system.name)}, declare: ${system.path}::__cognet_declare, body: ${system.path}::__COGNET_BODY },`),
            "];",
            "",
        ].join("\n")
    },

    /** One folder's files, each from where it sits (`#[path]`), and its folders as modules around theirs. */
    mount(node: Mount, indent: string, root: string, folders: string[]): string[] {
        const items = [
            ...node.files.map(file => [`${indent}#[path = ${JSON.stringify(relative(join(root, ...folders), file.absPath))}]`, `${indent}pub mod ${file.name};`]),
            ...[...node.folders].map(([name, folder]) => [`${indent}pub mod ${name} {`, ...library.mount(folder, `${indent}    `, root, [...folders, name]), `${indent}}`]),
        ]
        return items.flatMap((item, at) => (at === 0 ? item : ["", ...item]))
    },

    /** The two functions the runtime calls. */
    module(): string {
        return [
            "// Generated by axon prepare — the boundary the runtime calls this cognet's Rust systems through.",
            "use napi::bindgen_prelude::*;",
            "use napi::Either;",
            "use napi_derive::napi;",
            "",
            "/// The run protocol this module was built against — checked by the runtime before anything runs.",
            "#[napi]",
            "pub fn protocol() -> u32 {",
            "    cognet::PROTOCOL",
            "}",
            "",
            "/// How this module speaks to the runtime while an async system is going — set by `listen`.",
            "static OUT: std::sync::Mutex<Option<cognet::Out>> = std::sync::Mutex::new(None);",
            "",
            "/// The runtime's ear: every message an async run says goes here. Weak, so it never holds the process open;",
            "/// set again when a brain is loaded again in the same process.",
            "#[napi]",
            "pub fn listen(callback: napi::threadsafe_function::ThreadsafeFunction<String, Unknown<'static>, String, Status, false, true>) -> Result<()> {",
            "    let out: cognet::Out = std::sync::Arc::new(move |text: String| {",
            "        callback.call(text, napi::threadsafe_function::ThreadsafeFunctionCallMode::NonBlocking);",
            "    });",
            "    *OUT.lock().map_err(|_| Error::from_reason(\"the module's ear was poisoned\"))? = Some(out);",
            "    Ok(())",
            "}",
            "",
            "/// What the runtime tells an async run: a job, an answer, a cancel.",
            "#[napi]",
            "pub fn tell(text: String) -> Result<()> {",
            "    let out = OUT.lock().map_err(|_| Error::from_reason(\"the module's ear was poisoned\"))?.clone().ok_or_else(|| Error::from_reason(\"told before anyone listened\"))?;",
            "    cognet::tell(cognet_systems::SYSTEMS, &text, out).map_err(|fault| Error::from_reason(fault.message().to_string()))",
            "}",
            "",
            "/// Every system this module holds, and its declaration.",
            "#[napi]",
            "pub fn declarations(env: &Env) -> Result<Unknown<'_>> {",
            "    env.to_js_value(&cognet::declarations(cognet_systems::SYSTEMS))",
            "}",
            "",
            "/// What a run did: `{ changes, effects }` as JSON, and the typed arrays they mark.",
            "#[napi(object)]",
            "pub struct Ran {",
            "    pub ran: String,",
            "    pub arrays: Vec<Either5<Float64Array, Float32Array, Int32Array, Uint32Array, Uint8Array>>,",
            "}",
            "",
            "/// One run of the system named `name`: handed its snapshot as JSON and the bytes of every typed array it marks, by kind.",
            "#[napi]",
            "pub fn run(name: String, snapshot: String, kinds: Vec<String>, arrays: Vec<Uint8Array>) -> Result<Ran> {",
            "    let fail = |fault: cognet::Fault| Error::from_reason(fault.message().to_string());",
            "    if kinds.len() != arrays.len() {",
            "        return Err(Error::from_reason(format!(\"{} kinds for {} arrays\", kinds.len(), arrays.len())));",
            "    }",
            "    let blocks = kinds.iter().zip(arrays.iter()).map(|(kind, bytes)| cognet::Block::from_bytes(kind, bytes)).collect::<std::result::Result<Vec<_>, _>>().map_err(fail)?;",
            "    let snapshot = cognet::Snapshot::parse(&snapshot, blocks).map_err(fail)?;",
            "    let ran = cognet::serve(cognet_systems::SYSTEMS, &name, snapshot).map_err(fail)?;",
            "    let json = ran.json().map_err(fail)?;",
            "    let arrays = ran.blocks.into_iter().map(|block| match block {",
            "        cognet::Block::F64(values) => Either5::A(Float64Array::new(values)),",
            "        cognet::Block::F32(values) => Either5::B(Float32Array::new(values)),",
            "        cognet::Block::I32(values) => Either5::C(Int32Array::new(values)),",
            "        cognet::Block::U32(values) => Either5::D(Uint32Array::new(values)),",
            "        cognet::Block::U8(values) => Either5::E(Uint8Array::new(values)),",
            "    }).collect();",
            "    Ok(Ran { ran: json, arrays: arrays })",
            "}",
            "",
        ].join("\n")
    },
}

/** A folder of the cognet as the crate mounts it. */
type Mount = { files: Array<{ name: string; absPath: string }>; folders: Map<string, Mount> }
