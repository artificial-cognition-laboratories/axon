import { dirname } from "node:path"
import { getOption, ScalarType, type DescEnum, type DescExtension, type DescField, type DescFile, type DescMessage, type FileRegistry } from "@bufbuild/protobuf"
import { err } from "@arcforge/err"
import { arrayOf } from "./arrays"

/**
 * Rust — every schema of a cognet as one Rust module, `schema`: messages as
 * structs, enums as enums, unions as tagged enums, components as typed
 * handles, frames as named handles — each with serde attributes that make its JSON exactly the
 * TypeScript value's. Values cross from the TypeScript world to a Rust system
 * as JSON, and every typed array beside it as memory (`cognet::Array`), so
 * this agreement IS the contract: a field's JSON name, an enum's text, a
 * union's tag, what may be absent and what may be null are the same on both
 * sides. Plain functions, no I/O.
 *
 * Module paths follow the schemas' — `control/rhythm/rhythm.proto` is
 * `schema::control::rhythm::rhythm` — made into Rust names (`L0-measure` →
 * `l0_measure`, a keyword gets a trailing `_`); a component keeps its real
 * name (`"sense/L0-measure/inertia"`) as a string.
 */
export const rust = {
    /** The `schema` module: every file's types and handles, nested by path. */
    module(files: readonly DescFile[], registry: FileRegistry | null): string {
        if (!registry || files.length === 0) return "// Generated by axon prepare — this cognet declares no schemas.\n"
        const ctx: Ctx = { ext: Extensions(registry), registry: registry }
        const tree: Tree = { children: new Map(), body: [] }
        for (const file of [...files].sort((a, b) => (a.name < b.name ? -1 : 1))) {
            let node = tree
            for (const segment of file.name.split("/")) {
                const name = names.module(segment)
                const child = node.children.get(name) ?? { children: new Map(), body: [] }
                node.children.set(name, child)
                node = child
            }
            node.body.push(...emit.file(file, ctx))
        }
        return [`// Generated by axon prepare from this cognet's schemas — edit the schemas, not this file.`, "#![allow(dead_code, clippy::all)]", "", ...render(tree, "")].join("\n")
    },

    /** A path segment — a folder's or a file's name — as the Rust module it is: `L0-measure` → `l0_measure`, `rhythm.system` → `rhythm_system`. */
    segment(name: string): string {
        return names.module(name)
    },
}

type Tree = { children: Map<string, Tree>; body: string[] }

function render(node: Tree, indent: string): string[] {
    const lines = node.body.map(line => (line ? `${indent}${line}` : line))
    for (const [name, child] of node.children) {
        const uses = child.body.some(line => line.includes("Serialize")) ? [`${indent}    use ::cognet::serde::{Deserialize, Serialize};`, ""] : []
        lines.push(`${indent}pub mod ${name} {`, ...uses, ...render(child, `${indent}    `), `${indent}}`, "")
    }
    return lines
}

type Ext = ReturnType<typeof Extensions>

/** What emitting needs beyond the element: the runtime's options, and every schema, to find what a field names. */
type Ctx = { ext: Ext; registry: FileRegistry }

/** The runtime's options, from the image the schemas were compiled with. */
function Extensions(registry: FileRegistry) {
    const get = (name: string): DescExtension => {
        const found = registry.getExtension(name)
        if (!found) throw err("COGNET_SCHEMA_INVALID", { detail: `the runtime's schema defines no ${name} — the installed @arcforge/cognet is older than this platform` })
        return found
    }
    return {
        components: get("cognet.components"),
        frames: get("cognet.frames"),
        fixed: get("cognet.fixed"),
        keys: get("cognet.keys"),
        text: get("cognet.text"),
        union: get("cognet.union"),
        optional: get("cognet.optional"),
        nullable: get("cognet.nullable"),
        array: get("cognet.array"),
    }
}

/** What each schema element becomes — private to the emitter. */
const emit = {
    file(file: DescFile, ctx: Ctx): string[] {
        const lines: string[] = []
        for (const one of file.enums) lines.push(...emit.enumeration(one, ctx))
        for (const one of file.messages) lines.push(...emit.message(one, ctx))
        return lines
    },

    enumeration(desc: DescEnum, ctx: Ctx): string[] {
        const ext = ctx.ext
        const values = desc.values.filter(value => !(value.number === 0 && value.name.endsWith("_UNSPECIFIED")))
        const variants = values.map(value => ({ text: option.string(value, ext.text) || names.text(value.name, desc.name), name: names.variant(value.name, desc.name) }))
        return [
            ...docs.of(desc),
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]",
            `pub enum ${names.local(desc)} {`,
            ...variants.flatMap(variant => [`    #[serde(rename = ${JSON.stringify(variant.text)})]`, `    ${variant.name},`]),
            "}",
            "",
            `impl ${names.local(desc)} {`,
            "    /// Every value, in the schema's order.",
            `    pub const ALL: [Self; ${variants.length}] = [${variants.map(variant => `Self::${variant.name}`).join(", ")}];`,
            "",
            "    /// Its text, as the TypeScript side says it.",
            "    pub fn text(self) -> &'static str {",
            "        match self {",
            ...variants.map(variant => `            Self::${variant.name} => ${JSON.stringify(variant.text)},`),
            "        }",
            "    }",
            "}",
            "",
        ]
    },

    message(desc: DescMessage, ctx: Ctx): string[] {
        const ext = ctx.ext
        const lines: string[] = []
        for (const one of desc.nestedEnums) lines.push(...emit.enumeration(one, ctx))
        for (const one of desc.nestedMessages) lines.push(...emit.message(one, ctx))
        const folder = dirname(desc.file.name)
        const full = (field: DescField) => (folder === "." ? field.jsonName : `${folder}/${field.jsonName}`)
        if (option.boolean(desc, ext.frames)) {
            for (const field of desc.fields) lines.push(...docs.of(field), `pub const ${names.constant(field.name)}: ::cognet::Frame = ::cognet::Frame::new(${JSON.stringify(full(field))});`, "")
            return lines
        }
        if (option.boolean(desc, ext.components)) {
            for (const field of desc.fields) lines.push(...docs.of(field), `pub const ${names.constant(field.name)}: ::cognet::Component<${types.of(field, ctx)}> = ::cognet::Component::new(${JSON.stringify(full(field))});`, "")
            return lines
        }
        const tag = option.string(desc, ext.union)
        if (tag) return [...lines, ...emit.union(desc, tag)]
        const fields = desc.fields.flatMap(field => emit.field(field, ctx))
        return [...lines, ...docs.of(desc), "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", `pub struct ${names.local(desc)} {`, ...fields, "}", ""]
    },

    /** A field, with the serde that makes its JSON the TypeScript value's: its JSON name; absent when optional; null when nullable. */
    field(field: DescField, ctx: Ctx): string[] {
        const ext = ctx.ext
        const inner = types.of(field, ctx)
        const absent = field.proto.proto3Optional || option.boolean(field, ext.optional)
        const nullable = option.boolean(field, ext.nullable)
        const attributes: string[] = []
        // Named as its JSON is, whatever Rust calls it: `move` is `move_`, `relative_to` is `relativeTo`.
        if (field.jsonName !== names.field(field.name)) attributes.push(`rename = ${JSON.stringify(field.jsonName)}`)
        let type = inner
        if (absent && nullable) {
            type = `Option<Option<${inner}>>`
            attributes.push(`default`, `skip_serializing_if = "Option::is_none"`, `with = "::cognet::absent_or_null"`)
        } else if (absent) {
            type = `Option<${inner}>`
            attributes.push(`default`, `skip_serializing_if = "Option::is_none"`)
        } else if (nullable) {
            type = `Option<${inner}>`
        }
        return [...docs.of(field, "    "), ...(attributes.length ? [`    #[serde(${attributes.join(", ")})]`] : []), `    pub ${names.field(field.name)}: ${type},`]
    },

    /** A union: one variant a member, each the member's struct, tagged by `tag` as the TypeScript union is. */
    union(desc: DescMessage, tag: string): string[] {
        const oneof = desc.oneofs[0]
        if (desc.oneofs.length !== 1 || !oneof || desc.fields.some(field => field.oneof !== oneof)) {
            throw err("COGNET_SCHEMA_INVALID", { detail: `${desc.file.name}.proto, ${desc.name}: a union holds one oneof and nothing else` })
        }
        const variants = oneof.fields.map(field => {
            if (field.fieldKind !== "message") throw err("COGNET_SCHEMA_INVALID", { detail: `${desc.file.name}.proto, ${desc.name}.${field.name}: a union's members are messages` })
            return [`    #[serde(rename = ${JSON.stringify(field.jsonName)})]`, `    ${names.type(field.jsonName)}(${types.path(field.message)}),`]
        })
        return [...docs.of(desc), "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", `#[serde(tag = ${JSON.stringify(tag)})]`, `pub enum ${names.local(desc)} {`, ...variants.flat(), "}", ""]
    },
}

/** Field types in Rust — private to the emitter. */
const types = {
    of(field: DescField, ctx: Ctx): string {
        if (option.boolean(field, ctx.ext.array)) return `::cognet::Array<${arrayOf(field, option.number(field, ctx.ext.fixed)).rust}>`
        switch (field.fieldKind) {
            case "scalar":
                return types.scalar(field.scalar, field)
            case "enum":
                return types.path(field.enum)
            case "message":
                return types.path(field.message)
            case "list": {
                const element = field.listKind === "scalar" ? types.scalar(field.scalar, field) : field.listKind === "enum" ? types.path(field.enum) : types.path(field.message)
                const fixed = option.number(field, ctx.ext.fixed)
                return fixed > 0 ? `[${element}; ${fixed}]` : `Vec<${element}>`
            }
            case "map": {
                const value = field.mapKind === "scalar" ? types.scalar(field.scalar, field) : field.mapKind === "enum" ? types.path(field.enum) : types.path(field.message)
                const keys = option.string(field, ctx.ext.keys)
                if (keys) {
                    const found = ctx.registry.getEnum(keys) ?? ctx.registry.getEnum(`${field.parent.file.proto.package}.${keys}`)
                    if (!found) throw invalid(field, `its keys name the enum "${keys}", which no schema defines`)
                    return `::std::collections::BTreeMap<${types.path(found)}, ${value}>`
                }
                return `::std::collections::BTreeMap<${field.mapKey === ScalarType.STRING ? "String" : "i64"}, ${value}>`
            }
        }
    },

    /** A message or enum, by its path from the crate root — wherever it is used, it is the same path. */
    path(desc: DescMessage | DescEnum): string {
        return `crate::schema::${desc.file.name.split("/").map(names.module).join("::")}::${names.local(desc)}`
    },

    scalar(scalar: ScalarType, field: DescField): string {
        switch (scalar) {
            case ScalarType.DOUBLE:
                return "f64"
            case ScalarType.FLOAT:
                return "f32"
            case ScalarType.INT32:
            case ScalarType.SINT32:
            case ScalarType.SFIXED32:
                return "i32"
            case ScalarType.UINT32:
            case ScalarType.FIXED32:
                return "u32"
            case ScalarType.BOOL:
                return "bool"
            case ScalarType.STRING:
                return "String"
            case ScalarType.BYTES:
                return "::cognet::Array<u8>"
            default:
                throw invalid(field, "a 64-bit integer cannot cross as JSON — use double (envelope ms are doubles) or a 32-bit integer")
        }
    },
}

/** Options, read — private to the emitter. */
const option = {
    boolean(desc: Parameters<typeof getOption>[0], ext: DescExtension): boolean {
        return getOption(desc, ext) === true
    },
    number(desc: Parameters<typeof getOption>[0], ext: DescExtension): number {
        const value: unknown = getOption(desc, ext)
        return typeof value === "number" ? value : 0
    },
    string(desc: Parameters<typeof getOption>[0], ext: DescExtension): string {
        const value: unknown = getOption(desc, ext)
        return typeof value === "string" ? value : ""
    },
}

/** Rust names — private to the emitter. */
const names = {
    /** A message's or enum's name: nested ones carry their parents', as in TypeScript. */
    local(desc: DescMessage | DescEnum): string {
        const name = desc.parent ? `${names.local(desc.parent)}${desc.name}` : desc.name
        // `Self` is special syntax in Rust and cannot be used even as a raw identifier.
        return name === "Self" ? "SelfValue" : name
    },

    /** A path segment as a module: lowercase, words joined by `_`, a keyword set apart. */
    module(segment: string): string {
        const name = segment.replace(/[^A-Za-z0-9]+/g, "_").replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase()
        return KEYWORDS.has(name) ? `${name}_` : name
    },

    /** A field as a Rust field: its proto name, a keyword set apart. */
    field(name: string): string {
        return KEYWORDS.has(name) ? `${name}_` : name
    },

    /** A component's handle: SCREAMING_SNAKE of its field. */
    constant(name: string): string {
        return name.toUpperCase()
    },

    /** An enum value as a variant: its name less its enum's prefix, in UpperCamel. */
    variant(value: string, enumName: string): string {
        return names.type(names.text(value, enumName))
    },

    /** lowerCamel or snake as UpperCamel. */
    type(text: string): string {
        return text.replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, __, next: string) => next.toUpperCase())
    },

    /** An enum value's text: as the TypeScript generator says it. */
    text(value: string, enumName: string): string {
        const prefix = `${enumName.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase()}_`
        const rest = value.startsWith(prefix) ? value.slice(prefix.length) : value
        return rest.toLowerCase().replace(/_([a-z0-9])/g, (_, next: string) => next.toUpperCase())
    },
}

/** Rust's keywords, which no generated name may be. */
const KEYWORDS = new Set(["as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try", "typeof", "unsized", "virtual", "yield"])

/** Doc comments, from the schema's own — private to the emitter. */
const docs = {
    of(desc: DescMessage | DescEnum | DescField, indent = ""): string[] {
        const file = desc.kind === "field" ? desc.parent.file : desc.file
        const path = docs.path(desc)
        const text = file.proto.sourceCodeInfo?.location.find(one => one.path.length === path.length && one.path.every((step, at) => step === path[at]))?.leadingComments
        if (!text) return []
        const lines = text.split("\n").map(line => line.replace(/^ /, "").trimEnd())
        while (lines.length && lines[0] === "") lines.shift()
        while (lines.length && lines.at(-1) === "") lines.pop()
        return lines.map(line => `${indent}///${line ? ` ${line}` : ""}`)
    },

    path(desc: DescMessage | DescEnum | DescField): number[] {
        if (desc.kind === "field") return [...docs.path(desc.parent), 2, desc.parent.proto.field.indexOf(desc.proto)]
        if (desc.kind === "enum") return desc.parent ? [...docs.path(desc.parent), 4, desc.parent.proto.enumType.indexOf(desc.proto)] : [5, desc.file.proto.enumType.indexOf(desc.proto)]
        return desc.parent ? [...docs.path(desc.parent), 3, desc.parent.proto.nestedType.indexOf(desc.proto)] : [4, desc.file.proto.messageType.indexOf(desc.proto)]
    },
}

function invalid(field: DescField, why: string): Error {
    return err("COGNET_SCHEMA_INVALID", { detail: `${field.parent.file.name}.proto, ${field.parent.name}.${field.name}: ${why}` })
}
