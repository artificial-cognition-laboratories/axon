import { dirname, relative } from "node:path"
import { getOption, isMessage, ScalarType, toJson, type DescEnum, type DescExtension, type DescField, type DescFile, type DescMessage, type FileRegistry, type JsonValue } from "@bufbuild/protobuf"
import { err } from "@arcforge/err"
import { arrayOf } from "./arrays"

/** What emitting one schema file needs to know beyond it. */
export type Context = {
    registry: FileRegistry
    /** The module generated for a schema file's types: its absolute path, without extension. */
    types(file: DescFile): string
    /** The module generated for a schema file's handles: its absolute path, without extension. */
    handles(file: DescFile): string
    /** Where the frame a schema names is defined: its module (absolute, no extension) and its export. Throws on none, or two. */
    frame(name: string): { module: string; exported: string }
}

/** The header every generated module starts with — what `Schema` recognises as its own when cleaning up. */
export const HEADER = "// Generated by axon prepare from"

/**
 * TypeScript — one schema file as the TypeScript a cognet is written
 * against, in two modules. Its TYPES — enums as string unions with their
 * values listed, messages as plain types — are plain data, importable from
 * pure code and tests. Its HANDLES — components as `component<T>(...)`,
 * frames as `frame(...)` — need the runtime's globals, exactly as an author's
 * hand-written ones did, so discovery names them, typegen types them and the
 * bundle imports them as before. Plain functions, no I/O.
 *
 * Values stay plain data: a `repeated double` of fixed length is a tuple, one
 * marked `array` a `Float64Array`, an enum is its text, an `optional` field
 * may be absent. Nothing generated
 * wraps a value in a class, so a system writes `{ count: 1, at: now }`.
 */
export const typescript = {
    /** The modules for `file`, whose source is `named` (its path as it is imported): its types, and its handles when it declares any. */
    file(file: DescFile, named: string, context: Context): { types: string; handles: string | null } {
        const types = Module({ file: file, context: context, part: "types" })
        const handles = Module({ file: file, context: context, part: "handles" })
        const typeLines: string[] = []
        const handleLines: string[] = []
        for (const one of file.enums) typeLines.push(...types.enumeration(one))
        for (const one of file.messages) {
            typeLines.push(...types.message(one))
            handleLines.push(...handles.message(one))
        }
        const head = (out: ReturnType<typeof Module>) => [`${HEADER} ${named} — edit the schema, not this file.`, ...out.imports(), "", ...docs.file(file)]
        return {
            types: [...head(types), ...typeLines].join("\n"),
            handles: handleLines.length ? [...head(handles), ...handleLines].join("\n") : null,
        }
    },
}

/** One module being written — a file's types, or its handles: what it has to import, and how it says each thing. */
function Module(opts: { file: DescFile; context: Context; part: "types" | "handles" }) {
    const { file, context } = opts
    const here = opts.part === "types" ? context.types(file) : context.handles(file)
    /** Imports by module, each name with whether it is only a type. */
    const wanted = new Map<string, Map<string, boolean>>()
    const ext = {
        components: extension(context.registry, "cognet.components"),
        frames: extension(context.registry, "cognet.frames"),
        component: extension(context.registry, "cognet.component"),
        frame: extension(context.registry, "cognet.frame"),
        fixed: extension(context.registry, "cognet.fixed"),
        keys: extension(context.registry, "cognet.keys"),
        text: extension(context.registry, "cognet.text"),
        union: extension(context.registry, "cognet.union"),
        optional: extension(context.registry, "cognet.optional"),
        nullable: extension(context.registry, "cognet.nullable"),
        array: extension(context.registry, "cognet.array"),
    }

    function want(module: string, name: string, typeOnly: boolean): void {
        if (module === here) return
        const names = wanted.get(module) ?? new Map<string, boolean>()
        names.set(name, (names.get(name) ?? true) && typeOnly)
        wanted.set(module, names)
    }

    /** The TypeScript name of a message or enum, imported when another schema defines it. */
    function named(desc: DescMessage | DescEnum): string {
        const name = names.local(desc)
        want(context.types(desc.file), name, true)
        return name
    }

    function type(field: DescField): string {
        if (booleanOption(field, ext.array)) return arrayOf(field, numberOption(field, ext.fixed)).typescript
        switch (field.fieldKind) {
            case "scalar":
                return names.scalar(field.scalar, field)
            case "enum":
                return named(field.enum)
            case "message":
                return named(field.message)
            case "list": {
                const element = field.listKind === "scalar" ? names.scalar(field.scalar, field) : field.listKind === "enum" ? named(field.enum) : named(field.message)
                const fixed = numberOption(field, ext.fixed)
                return fixed > 0 ? `[${new Array<string>(fixed).fill(element).join(", ")}]` : `${element}[]`
            }
            case "map": {
                const value = field.mapKind === "scalar" ? names.scalar(field.scalar, field) : field.mapKind === "enum" ? named(field.enum) : named(field.message)
                const keys = stringOption(field, ext.keys)
                if (keys) return `Partial<Record<${named(enumNamed(keys, field))}, ${value}>>`
                return `Record<${field.mapKey === ScalarType.STRING ? "string" : "number"}, ${value}>`
            }
        }
    }

    function enumNamed(name: string, field: DescField): DescEnum {
        const found = context.registry.getEnum(name) ?? context.registry.getEnum(`${field.parent.file.proto.package}.${name}`)
        if (!found) throw invalid(field, `its keys name the enum "${name}", which no schema defines`)
        return found
    }

    return {
        imports(): string[] {
            return [...wanted].sort(([a], [b]) => (a < b ? -1 : 1)).map(([module, names]) => {
                const all = [...names].sort(([a], [b]) => (a < b ? -1 : 1))
                const typeOnly = all.every(([, only]) => only)
                const list = all.map(([name, only]) => (typeOnly || !only ? name : `type ${name}`)).join(", ")
                return `import ${typeOnly ? "type " : ""}{ ${list} } from ${JSON.stringify(specifier(here, module))}`
            })
        },

        enumeration(desc: DescEnum): string[] {
            const name = names.local(desc)
            const values = desc.values.filter(value => !(value.number === 0 && value.name.endsWith("_UNSPECIFIED"))).map(value => {
                const text = stringOption(value, ext.text)
                return text || names.text(value.name, desc.name)
            })
            return [...docs.of(desc), `export const ${name} = [${values.map(value => JSON.stringify(value)).join(", ")}] as const`, `export type ${name} = (typeof ${name})[number]`, ""]
        },

        /** A message: its type, in the types; its components or frames, in the handles. */
        message(desc: DescMessage): string[] {
            const lines: string[] = []
            if (opts.part === "types") for (const one of desc.nestedEnums) lines.push(...this.enumeration(one))
            for (const one of desc.nestedMessages) lines.push(...this.message(one))
            const holds = booleanOption(desc, ext.components) || booleanOption(desc, ext.frames)
            if (holds !== (opts.part === "handles")) return lines
            if (booleanOption(desc, ext.components)) {
                for (const field of desc.fields) lines.push(...docs.of(field), `export const ${field.jsonName} = component<${type(field)}>(${this.component(field)})`, "")
                return lines
            }
            if (booleanOption(desc, ext.frames)) {
                for (const field of desc.fields) lines.push(...docs.of(field), `export const ${field.jsonName} = frame(${this.frame(field)})`, "")
                return lines
            }
            const tag = stringOption(desc, ext.union)
            if (tag) return [...lines, ...docs.of(desc), `export type ${names.local(desc)} =`, ...this.union(desc, tag), ""]
            const fields = desc.fields.map(field => {
                if (field.oneof && !field.proto.proto3Optional) throw invalid(field, `a oneof is a union: mark its message with (cognet.union) = "kind", and give it nothing else`)
                const maybe = field.proto.proto3Optional || booleanOption(field, ext.optional)
                if (booleanOption(field, ext.optional) && field.fieldKind !== "list" && field.fieldKind !== "map") throw invalid(field, "(cognet.optional) is for repeated and map fields; any other field says `optional`")
                const nullable = booleanOption(field, ext.nullable) ? " | null" : ""
                return [...docs.of(field, "    "), `    ${field.jsonName}${maybe ? "?" : ""}: ${type(field)}${nullable}`]
            })
            return [...lines, ...docs.of(desc), `export type ${names.local(desc)} = {`, ...fields.flat(), "}", ""]
        },

        /** A union's members: each one of its oneof's messages, tagged by the field that holds it. */
        union(desc: DescMessage, tag: string): string[] {
            const oneof = desc.oneofs[0]
            if (desc.oneofs.length !== 1 || !oneof || desc.fields.some(field => field.oneof !== oneof)) {
                throw err("COGNET_SCHEMA_INVALID", { detail: `${desc.file.name}.proto, ${desc.name}: a union holds one oneof and nothing else` })
            }
            return oneof.fields.map((field, at) => {
                if (field.fieldKind !== "message") throw invalid(field, "a union's members are messages")
                return `    ${at === 0 ? " " : "|"} ({ ${tag}: ${JSON.stringify(field.jsonName)} } & ${named(field.message)})`
            })
        },

        /** A component's options, as the object `component()` takes. */
        component(field: DescField): string {
            const json = messageOption(field, ext.component)
            if (!json) return ""
            const opts: string[] = []
            const display = json.display
            if (isRecord(display)) {
                const parts: string[] = []
                for (const [key, value] of Object.entries(display)) {
                    if (key === "frame" && typeof value === "string") {
                        const defined = context.frame(value)
                        want(defined.module, defined.exported, false)
                        parts.push(`frame: ${defined.exported}`)
                    } else if (typeof value === "string" && /^[A-Z][A-Z0-9_]*$/.test(value)) {
                        parts.push(`${key}: ${JSON.stringify(enumText(value, key))}`)
                    } else {
                        parts.push(`${key}: ${JSON.stringify(value)}`)
                    }
                }
                opts.push(`display: { ${parts.join(", ")} }`)
            }
            return opts.length ? `{ ${opts.join(", ")} }` : ""
        },

        /** A frame's options, as the object `frame()` takes. */
        frame(field: DescField): string {
            const json = messageOption(field, ext.frame)
            if (!json) throw invalid(field, "a frame says what space it is with (cognet.frame)")
            const parts: string[] = []
            for (const [key, value] of Object.entries(json)) {
                if (key === "relativeTo" && typeof value === "string") {
                    const defined = context.frame(value)
                    want(defined.module, defined.exported, false)
                    parts.push(`relativeTo: ${defined.exported}`)
                } else if (key === "kind" && typeof value === "string") {
                    parts.push(`kind: ${JSON.stringify(enumText(value, key))}`)
                } else {
                    parts.push(`${key}: ${JSON.stringify(value)}`)
                }
            }
            return `{ ${parts.join(", ")} }`
        },
    }

    /** An enum option's value as its text: the name less its enum's prefix, in lowerCamel — or its `text` option. */
    function enumText(value: string, key: string): string {
        const owner = [...context.registry].find((desc): desc is DescEnum => desc.kind === "enum" && desc.file.proto.package === "cognet" && desc.values.some(one => one.name === value))
        const found = owner?.values.find(one => one.name === value)
        if (!owner || !found) throw err("COGNET_SCHEMA_INVALID", { detail: `${file.name}.proto: "${value}" is no value of cognet's ${key}` })
        return stringOption(found, ext.text) || names.text(value, owner.name)
    }
}

/** Names in TypeScript — private to the emitter. */
const names = {
    /** A message's or enum's name: nested ones carry their parents', `Chart` + `Because` → `ChartBecause`. */
    local(desc: DescMessage | DescEnum): string {
        return desc.parent ? `${names.local(desc.parent)}${desc.name}` : desc.name
    },

    /** An enum value's text: its enum's prefix taken off (`BEAT_NAME_RETINA` of `BeatName` → `RETINA`), in lowerCamel. */
    text(value: string, enumName: string): string {
        const prefix = `${enumName.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase()}_`
        const rest = value.startsWith(prefix) ? value.slice(prefix.length) : value
        return rest.toLowerCase().replace(/_([a-z0-9])/g, (_, next: string) => next.toUpperCase())
    },

    scalar(scalar: ScalarType, field: DescField): string {
        switch (scalar) {
            case ScalarType.BOOL:
                return "boolean"
            case ScalarType.STRING:
                return "string"
            case ScalarType.BYTES:
                return "Uint8Array"
            case ScalarType.DOUBLE:
            case ScalarType.FLOAT:
            case ScalarType.INT32:
            case ScalarType.UINT32:
            case ScalarType.SINT32:
            case ScalarType.FIXED32:
            case ScalarType.SFIXED32:
                return "number"
            default:
                // 64-bit integers would need bigint to be exact: a cognet's values are JSON, where a number is a double.
                throw invalid(field, "a 64-bit integer cannot cross as JSON — use double (envelope ms are doubles) or a 32-bit integer")
        }
    },
}

/** Doc comments, from the schema's own — private to the emitter. */
const docs = {
    /** An element's leading comment as a doc comment, or nothing. */
    of(desc: DescMessage | DescEnum | DescField, indent = ""): string[] {
        const file = desc.kind === "field" ? desc.parent.file : desc.file
        return docs.block(docs.leading(file, docs.path(desc)), indent)
    },

    /** The comment the schema opens with — above its `syntax` line — as the module's own. */
    file(file: DescFile): string[] {
        // Above `syntax` and set apart from it by a blank line, as a file's own comment is: protobuf calls that detached.
        const at = docs.at(file, [12])
        const block = docs.block([...(at?.leadingDetachedComments ?? []), ...(at?.leadingComments ? [at.leadingComments] : [])].join("\n"), "")
        return block.length ? [...block, ""] : []
    },

    /** A comment as a doc comment: one line on one line, more as a block. */
    block(text: string | undefined, indent: string): string[] {
        if (!text) return []
        const lines = text.split("\n").map(line => line.replace(/^ /, "").trimEnd())
        while (lines.length && lines[0] === "") lines.shift()
        while (lines.length && lines.at(-1) === "") lines.pop()
        if (lines.length === 0) return []
        if (lines.length === 1) return [`${indent}/** ${lines[0]} */`]
        return [`${indent}/**`, ...lines.map(line => `${indent} *${line ? ` ${line}` : ""}`), `${indent} */`]
    },

    /** The leading comment recorded at `path` in a file's descriptor. */
    leading(file: DescFile, path: number[]): string | undefined {
        return docs.at(file, path)?.leadingComments
    },

    /** What a file's descriptor records about the element at `path`. */
    at(file: DescFile, path: number[]) {
        return file.proto.sourceCodeInfo?.location.find(one => one.path.length === path.length && one.path.every((step, at) => step === path[at]))
    },

    /** Where in its file's descriptor an element sits — the path its comments are recorded under. */
    path(desc: DescMessage | DescEnum | DescField): number[] {
        if (desc.kind === "field") return [...docs.path(desc.parent), 2, desc.parent.proto.field.indexOf(desc.proto)]
        if (desc.kind === "enum") return desc.parent ? [...docs.path(desc.parent), 4, desc.parent.proto.enumType.indexOf(desc.proto)] : [5, desc.file.proto.enumType.indexOf(desc.proto)]
        return desc.parent ? [...docs.path(desc.parent), 3, desc.parent.proto.nestedType.indexOf(desc.proto)] : [4, desc.file.proto.messageType.indexOf(desc.proto)]
    },
}

/** The runtime's extension, from the image every schema was compiled with. */
function extension(registry: FileRegistry, name: string): DescExtension {
    const found = registry.getExtension(name)
    if (!found) throw err("COGNET_SCHEMA_INVALID", { detail: `the runtime's schema defines no ${name} — the installed @arcforge/cognet is older than this platform` })
    return found
}

function booleanOption(desc: Parameters<typeof getOption>[0], option: DescExtension): boolean {
    return getOption(desc, option) === true
}

function numberOption(desc: Parameters<typeof getOption>[0], option: DescExtension): number {
    const value: unknown = getOption(desc, option)
    return typeof value === "number" ? value : 0
}

function stringOption(desc: Parameters<typeof getOption>[0], option: DescExtension): string {
    const value: unknown = getOption(desc, option)
    return typeof value === "string" ? value : ""
}

/** A message option as its JSON — enum values by name, fields by their JSON names, defaults left out. Null when absent. */
function messageOption(desc: DescField, option: DescExtension): Record<string, JsonValue> | null {
    if (option.fieldKind !== "message") throw err("COGNET_SCHEMA_INVALID", { detail: `${option.typeName} is not a message option` })
    const value: unknown = getOption(desc, option)
    if (!isMessage(value, option.message)) return null
    const json = toJson(option.message, value)
    return isRecord(json) && Object.keys(json).length > 0 ? json : null
}

function isRecord(value: unknown): value is Record<string, JsonValue> {
    return typeof value === "object" && value !== null && !Array.isArray(value)
}

/** The import specifier from one module to another, both absolute and without extension. */
function specifier(from: string, to: string): string {
    const path = relative(dirname(from), to).split("\\").join("/")
    return path.startsWith(".") ? path : `./${path}`
}

function invalid(field: DescField, why: string): Error {
    return err("COGNET_SCHEMA_INVALID", { detail: `${field.parent.file.name}.proto, ${field.parent.name}.${field.name}: ${why}` })
}
