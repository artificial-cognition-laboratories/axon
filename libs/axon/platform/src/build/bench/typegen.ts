import { writeFile } from "node:fs/promises"
import { join } from "node:path"
import type { BenchAxis, BenchNormalizedConfig } from "@arcforge/types"
import { fsx } from "../../utils/fs"
import { Frame } from "../frame"

export type BenchTypegenResult = {
    axes: number
    measurements: number
    dimensions: number
    artifacts: number
}

function valueType(kind: BenchNormalizedConfig["measurements"][number]["value"]): string {
    if (kind.kind === "number") return "number"
    if (kind.kind === "boolean") return "boolean"
    if (kind.kind === "text") return "string"
    if (kind.values?.length) return kind.values.map(value => JSON.stringify(value)).join(" | ")
    return "string"
}

function dimensionType(value: BenchNormalizedConfig["dimensions"][number]["value"]): string {
    if (value.kind === "number") return "number"
    if (value.kind === "boolean") return "boolean"
    if (value.kind === "category" && !value.open) return value.values.map(item => JSON.stringify(item)).join(" | ") || "string"
    return "string"
}

/**
 * The union of variations declared on one axis, so `bench.axis("model")`
 * narrows to exactly what the matrix can produce rather than `unknown`.
 */
function axisRuntimeValue(axis: BenchAxis): string {
    const values = axis.values.map(item => JSON.stringify(item.value)).join(" | ")
    return values || "unknown"
}

export function benchDts(config: BenchNormalizedConfig): string {
    const measurements = config.measurements.map(item => `        ${JSON.stringify(item.id)}: ${valueType(item.value)}`).join("\n")
    const dimensions = config.dimensions.map(item => `        ${JSON.stringify(item.id)}?: ${dimensionType(item.value)}`).join("\n")
    const axes = config.axes.map(axis => `        ${JSON.stringify(axis.key)}: ${axisRuntimeValue(axis)}`).join("\n")
    const artifactIds = config.artifacts.length ? config.artifacts.map(item => JSON.stringify(item.id)).join(" | ") : "never"

    return `// .bench/bench.d.ts — generated by axon bench prepare — do not edit
import type { BenchObserveOptions } from "@arcforge/types"

type BenchMeasurements = {
${measurements}
}

type BenchDimensions = {
${dimensions}
}

type BenchAxes = {
${axes}
}

type GeneratedBenchOptions = Omit<BenchObserveOptions, "dimensions"> & {
    dimensions?: BenchDimensions
}

interface GeneratedBenchHandle {
    readonly workspace: import("@arcforge/types").BenchWorkspaceHandle
    axis<K extends keyof BenchAxes>(key: K): BenchAxes[K]
    observe<K extends keyof BenchMeasurements>(id: K, value: BenchMeasurements[K], options?: GeneratedBenchOptions): void
    attach(id: ${artifactIds}, content: unknown, options?: { mediaType?: string; schema?: string; role?: "evidence" | "output" | "replay" | "report" }): Promise<void>
}

declare module "bun:test" {
    interface TestContext {
        /** The agent's world for this trial. */
        workspace: import("@arcforge/types").BenchWorkspaceHandle
    }
}

declare global {
    const bench: GeneratedBenchHandle
    const observe: GeneratedBenchHandle["observe"]
    const Axon: () => Promise<Awaited<ReturnType<typeof import("@arcforge/core").Axon>> & { stop(): Promise<void> }>
    const defineBench: typeof import("@arcforge/types").defineBench
}

export {}
`
}

export function BenchTypegen(opts: { root: string }) {
    return {
        async write(config: BenchNormalizedConfig): Promise<BenchTypegenResult> {
            const out = Frame({ root: opts.root, kind: "bench" }).ensure("types")
            const declarations = benchDts(config)

            // Only the declarations derived from THIS config. The .bench
            // tsconfig and the root pointer into it belong to the shared frame
            // writer (project/typegen/tsconfig.ts), which runs first — writing
            // them here too meant two authors for one file, and the includes
            // silently drifted apart.
            await writeFile(join(out, "bench.d.ts"), declarations)

            // A bench nested inside another project must also be visible to
            // that project's scope, or `bench.observe` is untyped in its tests.
            // Into the host's `types/` area, which is what its tsconfig globs.
            const hostFrames = (["agent", "module", "cognet"] as const)
                .map(kind => Frame({ root: opts.root, kind: kind }))
                .filter(frame => fsx.exists(frame.dir))
            await Promise.all(hostFrames.map(frame =>
                writeFile(join(frame.ensure("types"), "bench.d.ts"), declarations)))
            return {
                axes: config.axes.length,
                measurements: config.measurements.length,
                dimensions: config.dimensions.length,
                artifacts: config.artifacts.length,
            }
        },
    }
}

export type BenchTypegenT = ReturnType<typeof BenchTypegen>
